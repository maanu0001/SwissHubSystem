/**
 * Die Laufliste einmal auspacken.
 *
 * Erst beim ersten Messen und dann gemerkt: die Karte wird pro Aufruf
 * gezeichnet, die Tabelle aendert sich nie.
 */
function packeAus(laeufe: string): Map<number, number> {
  const tabelle = new Map<number, number>();
  for (const lauf of laeufe.split(',')) {
    const [start, laenge, breite] = lauf.split(':');
    if (start === undefined || laenge === undefined || breite === undefined) {
      continue;
    }
    const erstes = Number.parseInt(start, 16);
    const anzahl = Number.parseInt(laenge, 16);
    const wert = Number.parseInt(breite, 16);
    for (let i = 0; i <= anzahl; i += 1) {
      tabelle.set(erstes + i, wert);
    }
  }
  return tabelle;
}

let normal: Map<number, number> | null = null;
let fett: Map<number, number> | null = null;

function tabelle(istFett: boolean): Map<number, number> {
  if (istFett) {
    fett ??= packeAus(LAEUFE_FETT);
    return fett;
  }
  normal ??= packeAus(LAEUFE_NORMAL);
  return normal;
}

/**
 * Die Breite eines Textes in Bildpunkten.
 *
 * Summiert die Vorschubbreiten der Zeichen. Kerning bleibt aussen vor: es
 * verschiebt die Gesamtbreite um Bruchteile eines Prozents, und die Tabelle
 * dafuer waere hundertmal so gross. Gezaehlt wird ueber Codepunkte und nicht
 * ueber `length`, damit ein Zeichen ausserhalb der Grundebene - ein Emoji
 * etwa - einmal zaehlt und nicht zweimal.
 */
export function messeText(text: string, schriftgrad: number, istFett = false): number {
  const breiten = tabelle(istFett);
  let einheiten = 0;
  for (const zeichen of text) {
    einheiten += breiten.get(zeichen.codePointAt(0) ?? 0) ?? ERSATZBREITE;
  }
  return (einheiten * schriftgrad) / EINHEITEN_JE_GEVIERT;
}

/**
 * Text auf eine Breite kuerzen - mit Auslassungszeichen, wenn noetig.
 *
 * Gemessen wird waehrend des Kuerzens, nicht ueber eine mittlere Zeichenbreite
 * geschaetzt. «WWWW» ist damit nach vier Zeichen zu Ende und «iiiiiiii» nicht.
 * Das Auslassungszeichen zaehlt mit, sonst ragt gerade der gekuerzte Text
 * ueber den Rand.
 */
export function kuerzeAufBreite(
  text: string,
  maxBreite: number,
  schriftgrad: number,
  istFett = false,
): string {
  const roh = text.trim();
  if (messeText(roh, schriftgrad, istFett) <= maxBreite) {
    return roh;
  }

  const zeichen = [...roh];
  const punkte = messeText('…', schriftgrad, istFett);
  let breite = 0;
  let anzahl = 0;
  for (const einzelnes of zeichen) {
    const naechste = breite + messeText(einzelnes, schriftgrad, istFett);
    if (naechste + punkte > maxBreite) {
      break;
    }
    breite = naechste;
    anzahl += 1;
  }
  // Passt nicht einmal ein Zeichen samt Punkten, bleibt das erste Zeichen
  // stehen: eine Karte mit einem einzelnen «…» sagt gar nichts mehr.
  return anzahl === 0 ? (zeichen[0] ?? '') : `${zeichen.slice(0, anzahl).join('')}…`;
}
